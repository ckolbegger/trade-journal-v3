// Post-build: generate the versioned, digest-complete Offline Release Inventory
// and the service worker that precaches exactly that set. Structural task D1-S2.
import { createHash } from 'node:crypto'
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { join, relative } from 'node:path'

const dist = 'dist'
const ignore = new Set(['sw.js', 'offline-inventory.json'])

async function walk(dir) {
  const out = []
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name)
    if (entry.isDirectory()) out.push(...await walk(path))
    else out.push(path)
  }
  return out
}

const files = (await walk(dist)).filter(f => !ignore.has(relative(dist, f)))
const entries = []
for (const file of files.sort()) {
  const bytes = await readFile(file)
  entries.push({
    url: '/' + relative(dist, file).replaceAll('\\', '/'),
    digest: 'sha256-' + createHash('sha256').update(bytes).digest('hex'),
  })
}
const release = 'sha256-' + createHash('sha256')
  .update(entries.map(e => `${e.url}:${e.digest}`).join('\n'))
  .digest('hex')

const inventory = { version: 1, release, entries }
await writeFile(join(dist, 'offline-inventory.json'), JSON.stringify(inventory, null, 2))

const sw = `// Generated by scripts/build-offline.mjs — do not edit.
const RELEASE = ${JSON.stringify(release)};
const ENTRIES = ${JSON.stringify(entries)};
const CACHE = 'tjv3-' + RELEASE;
self.addEventListener('install', event => {
  event.waitUntil(caches.open(CACHE).then(c => c.addAll(ENTRIES.map(e => e.url))).then(() => self.skipWaiting()));
});
self.addEventListener('activate', event => {
  event.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', event => {
  if (event.request.method !== 'GET') return;
  event.respondWith(caches.match(event.request).then(cached => cached || fetch(event.request)));
});
`
await writeFile(join(dist, 'sw.js'), sw)
console.log(`Offline Release Inventory ${release} with ${entries.length} assets`)
