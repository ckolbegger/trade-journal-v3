import { expect, test, type Page } from '@playwright/test'

async function setupClosedTrade(page: Page) {
  await page.goto('/')
  await expect(page.locator('main')).toHaveAttribute('data-view', /^(empty|ready)$/)
  if (await page.locator('[aria-label="Institutions"] li').count() === 0) {
    await page.getByLabel('Institution name').fill('Schwab')
    await page.getByRole('button', { name: 'Add institution' }).click()
  }
  if (await page.locator('[aria-label="Accounts"] li').count() === 0) {
    await page.locator('#acct-inst').selectOption({ label: 'Schwab' })
    await page.getByLabel('Account name').fill('Main')
    await page.getByRole('button', { name: 'Add account' }).click()
  }
  await page.getByRole('button', { name: 'New Plan' }).click()
  await page.getByLabel('Underlying').fill('AAPL')
  await page.getByLabel('Quantity').fill('10')
  await page.getByLabel('Entry price').fill('100')
  await page.getByLabel('Stop price').fill('95')
  await page.getByLabel('Target price').fill('110')
  await page.getByLabel('Thesis').fill('Why now')
  await page.getByLabel('Invalidation').fill('Close below 50d')
  await page.getByRole('button', { name: 'Confirm plan' }).click()
  await page.getByRole('region', { name: 'Planned trades' }).locator('.trade-row').filter({ hasText: 'AAPL' }).click()
  await page.getByRole('button', { name: 'Add execution' }).click()
  await page.getByLabel('Execution 1 instrument').fill('AAPL')
  await page.getByLabel('Execution 1 quantity').fill('10')
  await page.getByLabel('Execution 1 price').fill('100')
  await page.getByLabel('Execution 1 fee').fill('5')
  await page.getByLabel('Execution 1 economic time').fill('2026-11-20T20:00:00Z')
  await page.getByRole('radio', { name: 'Defer reflection' }).check()
  await page.getByRole('button', { name: 'Record position change' }).click()
  await page.getByRole('button', { name: 'Close position' }).click()
  const close = page.getByRole('form', { name: 'Close position' })
  await close.getByLabel('Close 1 instrument').fill('AAPL')
  await close.getByLabel('Close 1 quantity').fill('10')
  await close.getByLabel('Close 1 price').fill('110')
  await close.getByLabel('Close 1 fee').fill('4')
  await close.getByLabel('Close 1 economic time').fill('2026-11-23T20:00:00Z')
  await close.getByLabel('Close reason').selectOption('Target Reached')
  await close.getByRole('button', { name: 'Record close' }).click()
  await expect(page.getByTestId('closed-realized-pnl')).toHaveText('91.00')
}

const journalOutcomes = (page: Page) => page.evaluate(async () => {
  const db = await new Promise<IDBDatabase>((resolve, reject) => {
    const r = indexedDB.open('tjv3'); r.onsuccess = () => resolve(r.result); r.onerror = () => reject(r.error)
  })
  const rows = await new Promise<{ id: string; kind?: string; status?: string; definitionRevision?: string; source?: string }[]>((resolve, reject) => {
    const r = db.transaction('journal').objectStore('journal').getAll()
    r.onsuccess = () => resolve(r.result)
    r.onerror = () => reject(r.error)
  })
  return rows.filter(r => (r.id ?? '').includes('CloseReview'))
})

test('should offer Close Review only on a Closed detail and write nothing on leave', async ({ page }) => {
  await setupClosedTrade(page)
  await expect(page.getByRole('button', { name: 'Start Close Review' })).toBeVisible()
  await page.getByRole('button', { name: 'Start Close Review' }).click()
  const form = page.getByRole('form', { name: 'Close Review' })
  await form.getByLabel('Would you take this Trade again?').selectOption('No')
  await form.getByLabel('Key lesson').fill('wait for confirmation')
  await page.getByRole('button', { name: 'Review', exact: true }).click()
  await page.getByRole('button', { name: 'Trades' }).click()
  await page.getByRole('region', { name: 'Closed trades' }).locator('.trade-row').filter({ hasText: 'AAPL' }).click()
  expect(await journalOutcomes(page)).toEqual([])
  await expect(page.getByRole('form', { name: 'Close Review' })).toHaveCount(0)
})

test('should save one immutable D1 Entry with no Close Reason or Trade fact change', async ({ page }) => {
  await setupClosedTrade(page)
  await page.getByRole('button', { name: 'Start Close Review' }).click()
  const form = page.getByRole('form', { name: 'Close Review' })
  await form.getByRole('radio', { name: 'Complete review' }).check()
  await form.getByLabel('Would you take this Trade again?').selectOption('No')
  await form.getByLabel('What worked and what did not?').fill('entry was late')
  await form.getByLabel('Key lesson').fill('wait for confirmation')
  await form.getByRole('button', { name: 'Save Close Review' }).click()
  await expect(page.getByTestId('close-review-status')).toContainText('Saved')
  const rows = await journalOutcomes(page)
  expect(rows).toHaveLength(1)
  expect(rows[0].id).toMatch(/^entry-CloseReview:trade-aapl/)
  expect(rows[0]).toMatchObject({
    kind: 'Entry', definitionRevision: 'D1', source: 'Trade Close',
  })
  await expect(page.getByTestId('closed-reason')).toContainText('Target Reached')
})

test('should defer to a due Debt at the next Review and settle it from that Review', async ({ page }) => {
  await setupClosedTrade(page)
  await page.getByRole('button', { name: 'Start Close Review' }).click()
  const form = page.getByRole('form', { name: 'Close Review' })
  await form.getByRole('radio', { name: 'Defer review' }).check()
  await form.getByRole('button', { name: 'Save Close Review' }).click()
  await expect(page.getByTestId('close-review-status')).toContainText('Outstanding Debt')
  expect((await journalOutcomes(page)).map(r => r.kind)).toEqual(['Debt'])

  await page.getByRole('button', { name: 'Review', exact: true }).click()
  await expect(page.getByTestId('review-due-debt')).toContainText('CloseReview:trade-aapl')
  await page.getByLabel('Review TakeAgain').selectOption('Yes, as planned')
  await page.getByRole('button', { name: 'Answer Close Review debt' }).click()
  await expect(page.getByTestId('review-due-debt')).not.toContainText('CloseReview:trade-aapl')
  const rows = await journalOutcomes(page)
  expect(rows.map(r => r.kind).sort()).toEqual(['Debt', 'Entry'])
  expect(rows.find(r => r.kind === 'Entry')).toMatchObject({ definitionRevision: 'D1' })
})

