test('should show saved or deferred Close Review status on the Closed card', async ({ page }) => {
  await setupOpenTrade(page)
  await page.getByRole('button', { name: 'Trades', exact: true }).click()
  await page.getByRole('button', { name: 'Close position' }).click()
  const close = page.getByRole('form', { name: 'Close position' })
  await close.getByLabel('Close 1 instrument').fill('AAPL')
  await close.getByLabel('Close 1 quantity').fill('10')
  await close.getByLabel('Close 1 price').fill('105')
  await close.getByLabel('Close 1 fee').fill('2')
  await close.getByLabel('Close 1 economic time').fill('2026-11-24T20:00:00Z')
  await close.getByLabel('Close reason').selectOption('Target Reached')
  await close.getByRole('button', { name: 'Record close' }).click()
  await page.getByRole('button', { name: 'Review', exact: true }).click()
  const card = page.locator('.closed-card').first()
  await card.getByRole('button', { name: 'Write the Close Review' }).click()
  const dialog = page.getByRole('dialog', { name: 'Close Review' })
  await expect(dialog.getByRole('button', { name: 'Back to the Review' })).toBeVisible()
  await dialog.getByRole('button', { name: 'Back to the Review' }).click()
  await expect(dialog).toHaveCount(0)
  await card.getByRole('button', { name: 'Write the Close Review' }).click()
  const reviewDialog = page.getByRole('dialog', { name: 'Close Review' })
  await reviewDialog.getByLabel('Would you take this Trade again?').selectOption('Yes, as planned')
  await reviewDialog.getByLabel('What worked and what did not?').fill('waited for the Mark')
  await reviewDialog.getByLabel('Key lesson').fill('keep the stop')
  await reviewDialog.getByRole('button', { name: 'Save Close Review' }).click()
  await expect(page.getByRole('dialog', { name: 'Close Review' })).toHaveCount(0)
  const saved = await page.evaluate(async () => {
    const db = await new Promise<IDBDatabase>((resolve, reject) => {
      const r = indexedDB.open('tjv3'); r.onsuccess = () => resolve(r.result); r.onerror = () => reject(r.error)
    })
    return new Promise<{ kind?: string; obligationKey?: string }[]>((resolve, reject) => {
      const r = db.transaction('journal').objectStore('journal').getAll()
      r.onsuccess = () => resolve(r.result)
      r.onerror = () => reject(r.error)
    })
  })
  expect(saved.filter(r => String(r.obligationKey ?? '').startsWith('CloseReview:')).map(r => `${r.kind}:${r.obligationKey}`)).toEqual([
    'Entry:CloseReview:trade-aapl-2026-11-24',
  ])
  await page.getByRole('button', { name: 'Trades', exact: true }).click()
  await page.getByRole('button', { name: 'Review', exact: true }).click()
  expect(await card.getAttribute('data-close-review-status')).toBe('saved')
  await expect(card).toContainText('Close Review saved')
  await expect(card.getByRole('button', { name: 'Write the Close Review' })).toHaveCount(0)
})

