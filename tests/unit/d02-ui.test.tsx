it('opens the owed trigger-time form from global Journal Debt and renders settlement without a query read-back', async () => {
  const f = await openingFixture(); const saved = await f.workflows.recordPositionChange({ ...f.command, reflection: { kind: 'Defer' } });
  if (saved.status !== 'Recorded') throw new Error(saved.status);
  const user = userEvent.setup(); const journal = new Journal(f.store, f.runtime);
  const services = { workspace: f.workspace, catalog: f.catalog, workflows: f.workflows, views: new TradeViewsAndReporting(f.store), journal };
  render(<App services={services} />);
  await user.click(await screen.findByRole('button', { name: 'Journal Debt' }));
  await user.click(await screen.findByRole('button', { name: 'Answer reflection' }));
  await user.click(screen.getByLabelText('As Planned')); await user.click(screen.getByLabelText('Calm')); await user.selectOptions(screen.getByLabelText('Decision confidence'), '5');
  const query = vi.spyOn(journal, 'query');
  await user.click(screen.getByRole('button', { name: 'Save Debt outcome' }));
  expect(await screen.findByText('Reflection completed. Journal Debt settled.')).toBeTruthy();
  expect(query).not.toHaveBeenCalled();
  expect((await journal.query({ tradeId: f.command.tradeId })).obligations).toMatchObject([{ status: 'Completed', debtId: saved.journalOutcome.obligation.debtId }]);
  cleanup(); f.store.close();
});
